"""Write config/leancheck-books.txt: the order `leancheck section next` works through.

Topic order (building undergraduate mathematics bottom-up):
  Type Theory, Logic, Set Theory, Number Systems, Analysis (Kaplansky first),
  then the rest of Foundations, then the other folders, Calculus / Pre Calculus last; Physics is left out.
Inside a topic: fewest pages needing repair first (low-quality + damaged + old Tesseract pages, from
reports/audit.csv), so a batch finishes as many books as possible. Weaker copies listed in
config/lower-priority.txt go to the very end.

usage: python scripts/make_leancheck_list.py [--db PATH] [--data DIR] [--sources DIR]
"""
import argparse
import csv
import os
import re
import sqlite3
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
TOPICS = [
    ("Type Theory", ["Foundations/Type Theory/"]),
    ("Logic", ["Foundations/Logic/"]),                       # Fuzzy is split out below
    ("Set Theory", ["Foundations/Set Theory/"]),
    ("Number Systems", ["Foundations/NumberSystems/"]),
    ("Analysis", ["Analysis/"]),
    ("Foundations: Lambda Calculus, Computability, top level", ["Foundations/Lambda Calculus/",
                                                              "Foundations/Computability", "Foundations/"]),
    ("Foundations: Category Theory", ["Foundations/Category Theory/"]),
    ("Foundations: Model Theory", ["Foundations/Model Theory/"]),
    ("Foundations: Proof Theory", ["Foundations/Proof Theory/"]),
    ("Foundations: Lattice and Order Theory", ["Foundations/Lattice and Order Theory/"]),
    ("Foundations: Fuzzy logic, Reference", ["Foundations/Logic/Fuzzy/", "Foundations/Reference/"]),
    ("Measure Theory", ["Measure Theory/"]),
    ("Topology", ["Topology/"]),
    ("Algebra", ["Algebra/"]),
    ("Number Theory", ["Number Theory/"]),
    ("Geometry", ["Geometry/"]),
    ("Combinatorics and Graph Theory", ["Combinatorics and Graph Theory/"]),
    ("Differential Equations", ["Differential Equations/"]),
    ("Numerical Analysis", ["Numerical Analysis/"]),
    ("Applied", ["Applied/"]),
    ("Computer Science", ["Computer Science/"]),
    ("History", ["History/"]),
    ("Calculus and Pre Calculus", ["Calculus/", "Pre Calculus/"]),
]
FIRST = ["Analysis/Metric Spaces/Set Theory and Metric Spaces - Kaplansky.pdf"]
SKIP = ("Physics/",)


def topic_of(path: str) -> int | None:
    if path.startswith(SKIP):
        return None
    best, best_len = None, -1
    for i, (_, prefixes) in enumerate(TOPICS):
        for pre in prefixes:
            if path.startswith(pre) and len(pre) > best_len:
                best, best_len = i, len(pre)
    return best


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=os.environ.get("LIBRARIAN_DATA", r"D:\Readings\librarian"))
    ap.add_argument("--sources", default=os.environ.get("LIBRARIAN_SOURCES", r"D:\Readings\Sources"))
    a = ap.parse_args()
    data, sources = Path(a.data), Path(a.sources)
    con = sqlite3.connect(f"file:{(data / 'librarian.sqlite').as_posix()}?mode=ro&immutable=1", uri=True)
    audit = {r["sha256"]: r for r in csv.DictReader((data / "reports" / "audit.csv").open(encoding="utf-8"))}
    lower = [l.strip() for l in (REPO / "config" / "lower-priority.txt").read_text(encoding="utf-8").splitlines()
             if l.strip() and not l.startswith("#")]
    groups: dict[int, list] = {}
    tail = []
    for sha, path, pages in con.execute("SELECT sha256, path, pdf_pages FROM books WHERE status != 'unsupported'"):
        if not (sources / path).is_file():
            continue
        r = audit.get(sha, {})
        legacy = int(m.group(1)) if (m := re.search(r"legacy:(\d+)", r.get("methods", ""))) else 0
        repairs = int(r.get("low") or 0) + int(r.get("damaged") or 0) + legacy
        item = (repairs, pages or 0, path)
        if path in lower:
            tail.append(item)
            continue
        t = topic_of(path)
        if t is not None:
            groups.setdefault(t, []).append(item)
    out = ["# Generated by scripts/make_leancheck_list.py; edit freely (it is only regenerated on request).",
           "# `scripts\\run.ps1 leancheck section next [--budget N]` takes books from the top that have no report yet.",
           "# After #: pages needing repair (low + damaged + old Tesseract pages), PDF pages.", ""]
    total = 0
    for t in sorted(groups):
        items = sorted(groups[t], key=lambda x: (x[2] not in FIRST, x[0], x[1], x[2]))
        out.append(f"## {TOPICS[t][0]} ({len(items)} books)")
        out += [f"{p}  # repairs {rep}, {n} pp" for rep, n, p in items]
        out.append("")
        total += len(items)
    out.append(f"## Weaker copies of books listed above ({len(tail)}; config/lower-priority.txt)")
    out += [f"{p}  # repairs {rep}, {n} pp" for rep, n, p in sorted(tail, key=lambda x: (x[0], x[1]))]
    (REPO / "config" / "leancheck-books.txt").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"{total} books in {len(groups)} topics + {len(tail)} weaker copies -> config/leancheck-books.txt")


if __name__ == "__main__":
    main()
